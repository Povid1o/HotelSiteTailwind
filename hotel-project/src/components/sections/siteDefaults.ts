const filled = (v: unknown): boolean =>
  typeof v === 'string' ? v.trim() !== '' : typeof v === 'object' && v !== null && !(v instanceof File) && !Array.isArray(v) ? Object.values(v).some(filled) : !!v;

/** Сохранённое значение побеждает, если оно непустое; иначе берётся значение по умолчанию. */
export const mergeDefaults = (key: string, saved: unknown): Rec => {
  const source: Rec = typeof saved === 'object' && saved !== null && !Array.isArray(saved) ? (saved as Rec) : {};
  if (!DEFAULTS[key]) return source;
  const out: Rec = { ...DEFAULTS[key], ...source };
  Object.keys(source).forEach((field) => {
    const value = source[field];
    const isEmpty = Array.isArray(value) ? !value.some((item) => item instanceof File || filled(item)) : typeof value === 'string' ? !value.trim() : value === undefined || value === null;
    if (isEmpty) out[field] = DEFAULTS[key][field] ?? (Array.isArray(value) ? [] : value);
  });
  return out;
};

/** Раздел для сайта: значения по умолчанию + то, что заполнено в админке; null, если владелец скрыл блок. */
export const sec = (key: string, saved: unknown): Rec | null => {
  const merged = mergeDefaults(key, saved);
  return merged.hidden === true ? null : merged;
};
